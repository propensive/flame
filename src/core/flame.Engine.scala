package flame

// The REPL as an interface sees it: a channel of requests and replies. A reply is correlated
// by the id the engine mints for the request; replies the engine pushes of its own accord (a
// pending submission's streamed output, its final reply) reach the sink by that id too.
// The terminal client's engine is the socket to the server process; the web's is the
// in-process `Sessions.Connection`.
trait Engine:
  def request(request: Int => Repl.Request)(reply: Repl.Reply => Unit): Unit
  def send(request: Int => Repl.Request): Unit
  def pushed(sink: Repl.Reply => Unit): Unit
  def close(): Unit
