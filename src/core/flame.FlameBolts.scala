package flame

// The bolt codes of Flame, which begin `↯/f`, as those of Pyrocosm and its other tools do
// (`pyrocosm.Bolts`). Each module of Flame is a subdivision, numbered after Pyrocosm's own and
// those of the tools before it; the record of what every code means is `f.tel` in
// propensive/bolt.
object FlameBolts:
  final val core     = 17
  final val web      = 18
  final val client   = 19
  final val launcher = 20

  // The code of the `error`th error of `subdivision`, or of its `variant`th variant.
  def apply(subdivision: Int, error: Int, variant: Int = 0): fulminate.Bolt =
    pyrocosm.Bolts(subdivision, error, variant)

  // The code of a throwable which a failure is reported on account of, for the failure's code to
  // carry: a fulminate error's own, and none for any other.
  def of(error: Throwable): fulminate.Bolt = error match
    case error: fulminate.Error => error.bolt
    case _                      => fulminate.Bolt.Uncoded
